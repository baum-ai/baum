/** A brand's mark. Decorative by default, because it sits beside the name it
 *  stands for; give it a `title` when it stands alone. */
export function BrandMark({
  brand,
  size = 14,
  className,
  title,
}: {
  brand: Brand;
  size?: number;
  className?: string;
  title?: boolean;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      fillRule="evenodd"
      aria-hidden={title ? undefined : "true"}
      role={title ? "img" : undefined}
      aria-label={title ? NAMES[brand] : undefined}
      focusable="false"
      // Always the vendor's own colour: the marks are not ours to recolour.
      style={{ color: `var(--brand-mark-${brand})` }}
      className={cn("flex-none", className)}
    >
      {MARKS[brand].map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}

function Named({
  brand,
  label,
  size,
  className,
}: {
  brand: Brand | null;
  label: ReactNode;
  size?: number;
  className?: string;
}) {
  return (
    <span className={cn("inline-flex min-w-0 items-center gap-1.5", className)}>
      {brand ? <BrandMark brand={brand} size={size} /> : null}
      <span className="min-w-0 truncate">{label}</span>
    </span>
  );
}

/** A harness by its product name with its mark before it: `claude_code`
 *  reads as the Claude mark and "Claude Code". */
export function HarnessName({
  vendor,
  size,
  className,
}: {
  vendor: string;
  size?: number;
  className?: string;
}) {
  return (
    <Named
      brand={harnessBrand(vendor)}
      label={harnessName(vendor)}
      size={size}
      className={className}
    />
  );
}

/** A model id as recorded, with its maker's mark before it. A host that folds
 *  models under a placeholder name passes the `label` to show instead. */
export function ModelName({
  model,
  label = model,
  size,
  className,
}: {
  model: string;
  label?: string;
  size?: number;
  className?: string;
}) {
  return <Named brand={modelBrand(model)} label={label} size={size} className={className} />;
}
