// Writes the custom tile kit's design tokens and fonts (oss/tiles/kit/tokens.css
// and fonts.css) from the viewer's palette, type scale and fonts and the
// app's radii, so a tile looks like the app around it. `--check` writes
// nothing and fails when the committed files differ from what it would write;
// `pnpm check` runs it that way. See "Custom tile kit" in oss/ARCHITECTURE.md.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const oss = resolve(app, "..");
const viewer = join(oss, "viewer/src");
const kit = join(oss, "tiles/kit");

/** The type steps a tile may use, as the UI guide names them. */
const STEPS = ["xs", "base", "lg", "2xl", "3xl"];
/** The font files inlined into every frame: Latin, upright. Latin Extended
 *  and italics fall back to the system's faces and synthesised italics. */
const FONT_FILES = ["instrument-sans-latin-wght-normal.woff2", "manrope-latin-wght-normal.woff2"];

const HEADER = (what) =>
  `/* Generated by oss/app/scripts/build-tile-kit.mjs from ${what}.\n   Do not edit: run \`node scripts/build-tile-kit.mjs\` in oss/app. */\n`;

const read = (path) => readFileSync(path, "utf8");

/** CSS without its comments or blank lines: every frame carries it. */
const bare = (css) =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== "")
    .join("\n");

/** The declarations of one property pattern inside a block of CSS. */
function declarations(css, pattern) {
  return [...css.matchAll(pattern)].map((match) => `  ${match[1]}: ${match[2].trim()};`);
}

/** The body of the first block that `selector` opens in `css`. */
function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`no "${selector} {" block`);
  const open = css.indexOf("{", start);
  let depth = 0;
  for (let index = open; index < css.length; index++) {
    if (css[index] === "{") depth++;
    if (css[index] === "}" && --depth === 0) return css.slice(open + 1, index);
  }
  throw new Error(`unclosed "${selector}" block`);
}

function tokens() {
  const palette = read(join(viewer, "palette.css"));
  const custom = read(join(viewer, "themes/custom.css"));
  const scale = block(read(join(viewer, "viewer.css")), "@theme");
  const fonts = block(read(join(viewer, "fonts/fonts.css")), ":root");
  const style = block(read(join(app, "src/style.css")), ":root");

  const type = STEPS.flatMap((step) => {
    const size = new RegExp(`(--text-${step}):\\s*([^;]+);`).exec(scale);
    const height = new RegExp(`(--text-${step}--line-height):\\s*([^;]+);`).exec(scale);
    if (!size || !height) throw new Error(`viewer.css has no --text-${step} step`);
    return [`  ${size[1]}: ${size[2].trim()};`, `  ${height[1]}: ${height[2].trim()};`];
  });
  const families = [
    ...declarations(fonts, /(--font-(?:text|heading)):([^;]+);/g),
    ...declarations(scale, /(--font-mono):([^;]+);/g),
  ];
  const radii = declarations(style, /(--radius-(?:xs|sm|md|lg)):([^;]+);/g);
  if (families.length !== 3) throw new Error("expected --font-text, --font-heading, --font-mono");
  if (radii.length !== 4) throw new Error("expected the app's four --radius-* overrides");

  return [
    HEADER(
      "oss/viewer/src/palette.css, themes/custom.css, viewer.css, fonts/fonts.css and oss/app/src/style.css",
    ),
    "/* The palette and the theme's overrides, as the viewer layers them\n   (theme.css): dark mode keys on :root[data-theme=\"dark\"], which the kit\n   sets from the app's theme. */",
    "@layer baum-palette, baum-theme;",
    `@layer baum-palette {\n${bare(palette)}\n}`,
    `@layer baum-theme {\n${bare(custom)}\n}`,
    "/* The type scale, families and the app's radii. */",
    `:root {\n${[...type, ...families, ...radii].join("\n")}\n}`,
    "",
  ].join("\n");
}

function fonts() {
  const css = read(join(viewer, "fonts/fonts.css"));
  const faces = [...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map((match) => match[0]);
  const inlined = FONT_FILES.map((file) => {
    const face = faces.find((candidate) => candidate.includes(`./${file}`));
    if (!face) throw new Error(`fonts.css declares no face for ${file}`);
    const data = readFileSync(join(viewer, "fonts", file)).toString("base64");
    return face.replace(`url("./${file}")`, `url("data:font/woff2;base64,${data}")`);
  });
  return `${HEADER("oss/viewer/src/fonts (SIL Open Font License)")}${inlined.join("\n")}\n`;
}

const outputs = [
  { path: join(kit, "tokens.css"), content: tokens() },
  { path: join(kit, "fonts.css"), content: fonts() },
];

if (process.argv.includes("--check")) {
  const stale = outputs.filter(({ path, content }) => {
    try {
      return read(path) !== content;
    } catch {
      return true;
    }
  });
  if (stale.length > 0) {
    for (const { path } of stale) console.error(`${path} is out of date.`);
    console.error("Run `node scripts/build-tile-kit.mjs` in oss/app and commit the result.");
    process.exit(1);
  }
} else {
  for (const { path, content } of outputs) writeFileSync(path, content);
}
