package bundle

import "testing"

func TestFlagBotContributionRecognizedTools(t *testing.T) {
	cases := []struct {
		name        string
		item        ConversationItem
		wantBot     bool
		wantBotTool string
		wantReport  bool
	}{
		{
			name:        "explicit Claude disclosure",
			item:        ConversationItem{Body: "Generated by Claude Code from an agent session."},
			wantBot:     true,
			wantBotTool: "Claude",
		},
		{
			name:        "explicit Codex disclosure",
			item:        ConversationItem{Body: "codex-pull-request-review-summary"},
			wantBot:     true,
			wantBotTool: "Codex",
		},
		{
			name:        "GitHub-reported bot actor with a recognisable login",
			item:        ConversationItem{Bot: true, AuthorLogin: "cursor-bot"},
			wantBot:     true,
			wantBotTool: "Cursor",
		},
		{
			// A disclosure match always means automation, even with no recognized
			// tool name. Requiring BotTool != "" used to mis-flag this as a human
			// comment.
			name:        "generic disclosure naming no recognised tool",
			item:        ConversationItem{Body: "Generated by an internal automation tool."},
			wantBot:     true,
			wantBotTool: "",
		},
		{
			name: "ordinary human comment",
			item: ConversationItem{Bot: false, AuthorLogin: "alice", Body: "Looks good to me."},
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			item := c.item
			FlagBotContribution(&item)
			if item.Bot != c.wantBot {
				t.Errorf("Bot = %v, want %v", item.Bot, c.wantBot)
			}
			if item.BotTool != c.wantBotTool {
				t.Errorf("BotTool = %q, want %q", item.BotTool, c.wantBotTool)
			}
			if item.BotReport != c.wantReport {
				t.Errorf("BotReport = %v, want %v", item.BotReport, c.wantReport)
			}
		})
	}
}
